export function normalizePath(path) {
  if (!path) return "/";
  const cleaned = path.replace(/\/+$/, "");
  return cleaned === "" ? "/" : cleaned;
}

export function getRouteSeo(pathname) {
  const normalized = normalizePath(pathname);
  return ROUTES_SEO[normalized] || DEFAULT_SEO;
}
